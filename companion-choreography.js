// Phrase anchors keep cached TTS text intact while following its character progress.
export const COMPANION_CUES=Object.fromEntries([...niaBook.pages,...finBook.pages].map(page=>{
 const cues=PLANS[page.scene].map(([phrase,target,action])=>{
  const at=page.text.indexOf(phrase);if(at<0)throw new Error(`Missing narration cue phrase: ${phrase}`);
  return {target,action,progress:at/page.text.length};
 }).sort((a,b)=>a.progress-b.progress);
 return [page.scene,cues];
}));
